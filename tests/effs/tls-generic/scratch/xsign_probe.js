// scratch/xsign_probe.js -- hermetic: the trust anchor is an identity.
//
// A root that re-issues its own subject under a different issuer (a
// cross-sign, how a CA migrates its root without breaking the peers that
// already trust it) has to END the chain: the peer sends that cross-cert
// as its last certificate, and the issuer it names is in no store. Both
// OpenSSL and node match a trust anchor by subject + public key.
//
// The portable lane matched raw bytes instead, so the walk ran out of
// issuers and answered 614 UNABLE_TO_GET_ISSUER_CERT_LOCALLY -- measured
// on cloudflare.com and example.com (their chains end in a cross-signed
// SSL.com root), which made every verified fetch of a real host fail
// after the lane was installed. No gate could see it: the badssl rungs
// are reachable only with a network, and none of them cross-signs.
//
// The chain and the trust store are generated by the gate with openssl
// (see tls-generic.sh), so this probe is hermetic and network-free:
//   xroot.pem    self-signed, subject "XSign Root", key A  -- the store
//   xother.pem   self-signed, subject "XSign Root", key B
//   xcross.pem   subject "XSign Root", key A, signed by xother
//   xleaf.pem    CN=localhost, signed by xroot (key A)
//   ximp.pem     subject "XSign Root", key C, signed by xother
//   ximpleaf.pem CN=localhost, signed by ximp (key C)
//
// Usage: xsign_probe.js <dir>    (default: the repo's tests/io material)
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");
const rt = require("./rt_path.js");

const dir = process.argv[2] || "/tmp/opencode/xsign";

const X = (f) => new crypto.X509Certificate(
  fs.readFileSync(path.join(dir, f)));
const root = X("xroot.pem");
const other = X("xother.pem");
const cross = X("xcross.pem");
const leaf = X("xleaf.pem");
const imp = X("ximp.pem");
const impleaf = X("ximpleaf.pem");

let pass = 0;
let fail = 0;

// The verdict verify_chain gives a chain and a store: "ok" or the message
// it refused with. verify_chain throws, so a refusal is the value here.
// Passing no store is the production call, and it must still answer a
// VERDICT: a store read as a TypeError ("Cannot read properties of
// undefined (reading 'find')") is what the first cut of this fix did,
// and the badssl rungs of the ladder answered 614 for every host.
const verdict = (ders, host, roots) => {
  try {
    rt.verify_chain(ders, host, undefined, roots);
    return "ok";
  } catch (e) {
    return String(e.message);
  }
};

// Both texts mean "no path to a trust anchor": the second is what a
// certificate whose subject is its own issuer reads as. Either one is a
// refusal, and either one would let an impostor through if this rung
// accepted it, so the rung names both.
const REFUSED = "UNABLE_TO_GET_ISSUER_CERT_LOCALLY|SELF_SIGNED_CERT_IN_CHAIN";
function is_refused(label, got) {
  if (got !== "ok" && REFUSED.split("|").indexOf(got) >= 0) {
    pass += 1;
    console.log("PASS " + label);
  } else {
    fail += 1;
    console.log("FAIL " + label + ": want refused, got " + got);
  }
}

function is(label, got, want) {
  if (got === want) {
    pass += 1;
    console.log("PASS " + label);
  } else {
    fail += 1;
    console.log("FAIL " + label + ": want " + want + ", got " + got);
  }
}

// The cross-cert is NOT the root: different issuer, different bytes. If
// the store ever carries it verbatim this rung would pass for the wrong
// reason, so that is asserted before anything else.
is("the cross-cert is a different certificate from the trusted root",
  cross.raw.equals(root.raw), false);
is("the cross-cert carries the root's subject and key",
  cross.subject === root.subject
    && cross.publicKey.export({ format: "der", type: "spki" })
      .equals(root.publicKey.export({ format: "der", type: "spki" })),
  true);

// The regression: the peer sends the leaf and root's cross-sign, and the
// store has the root. Before the fix this answered
// UNABLE_TO_GET_ISSUER_CERT_LOCALLY, because the only issuer named for
// the cross-cert is "XSign Root" and no store entry BY THAT NAME signs
// it -- the anchor has the same name, not the same outbound issuer.
is("a cross-signed root ends the chain",
  verdict([leaf.raw, cross.raw], "localhost", [root]), "ok");

// The ordinary shape still works: one issuer, found in the store.
is("an ordinary chain still ends at the store root",
  verdict([leaf.raw], "localhost", [root]), "ok");

// Fail closed: an identity the store does not hold is not an anchor.
// ximp has the root's SUBJECT but a different key, so a matching subject
// alone must not buy trust -- the walk has to find an issuer for it and
// there is none.
is_refused("the same subject with a different key is not an anchor",
  verdict([impleaf.raw, imp.raw], "localhost", [root]));

// And no store at all is no chain, self-signed name notwithstanding.
is_refused("an empty store refuses every chain",
  verdict([leaf.raw, cross.raw], "localhost", []));

// The hostname check stays fail-closed whatever the chain does.
is("a chain for another host is still refused",
  verdict([leaf.raw, cross.raw], "not-localhost", [root]),
  "ERR_TLS_CERT_ALTNAME_INVALID");

// Production passes no store and gets the host's, which knows nothing
// about XSign Root. The point of the case is the SHAPE of the answer: a
// refusal, never a TypeError from reading a store that was never resolved.
// A store read as undefined is how the first cut of this fix answered 614
// "Cannot read properties of undefined (reading 'find')" on every
// verified handshake -- the ladder's badssl rungs caught it, this case
// keeps it caught. Either refusal text is fine here: the host store
// matches the cross-cert by SUBJECT, not by issuer, and a certificate
// whose subject is its own issuer reads as self-signed.
is_refused("the host store is used when no store is passed",
  verdict([leaf.raw, cross.raw], "localhost"));

console.log((pass + fail) + " cases, " + fail + " failed");
if (fail > 0) {
  process.exit(1);
}
